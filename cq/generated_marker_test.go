package cq

import (
	"fmt"
	"strings"
	"testing"
)

func TestALanguagesOwnGeneratedMarkerIsFoundOnAnyOfTheFirstFortyLines(t *testing.T) {
	tab, err := LoadTable()
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range []struct{ file, lang, marker string }{
		{"main.tf", "hcl", "# managed by terraform"},
		{"Makefile", "makefile", "# generated by automake"},
	} {
		if got := tab.Detect(c.file, nil); got != c.lang {
			t.Fatalf("%s is read as %q, and this test needs %q", c.file, got, c.lang)
		}

		file := func(at int, line string) []byte {
			lines := make([]string, 60)
			for i := range lines {
				lines[i] = fmt.Sprintf("# Copyright 2026 Example, line %d", i+1)
			}
			if at > 0 {
				lines[at-1] = line
			}
			return []byte(strings.Join(lines, "\n") + "\n")
		}
		for _, tc := range []struct {
			name string
			text []byte
			want bool
		}{
			{"the marker on line 1", file(1, c.marker), true},
			{"the marker on line 2, under an ordinary header", file(2, c.marker), true},
			{"the marker on line 40", file(40, c.marker), true},
			{"the marker on line 41", file(41, c.marker), false},
			{"no marker", file(0, ""), false},
			{"this file is, on line 1", file(1, "# This file is the entry point"), true},
			{"this file is, on line 2", file(2, "# This file is the entry point"), false},
		} {
			t.Run(c.lang+"/"+tc.name, func(t *testing.T) {
				if got := tab.IsGenerated(c.lang, tc.text); got != tc.want {
					t.Fatalf("IsGenerated is %t, and %t is required", got, tc.want)
				}
			})
		}
	}
}
